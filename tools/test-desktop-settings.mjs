// Headless UI check against fictional, in-memory preferences. No real Tauri IPC.
import {createRequire} from 'node:module';
import {fileURLToPath,pathToFileURL} from 'node:url';
import path from 'node:path';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const requireFrontend=createRequire(path.join(root,'frontend/package.json'));
const {createServer}=await import(pathToFileURL(path.join(root,'frontend/node_modules/vite/dist/node/index.js')).href);
const {svelte}=await import(pathToFileURL(path.join(root,'frontend/node_modules/@sveltejs/vite-plugin-svelte/src/index.js')).href);
const preprocess=requireFrontend('svelte-preprocess');
const {chromium}=process.env.JARVIS_TEST_NODE_MODULES?createRequire(path.join(process.env.JARVIS_TEST_NODE_MODULES,'playwright/package.json'))('playwright'):requireFrontend('playwright');
const server=await createServer({configFile:false,root:path.join(root,'frontend'),plugins:[svelte({preprocess:preprocess({typescript:true}),onwarn:(warning,handler)=>{if(warning.code!=='css-unused-selector')handler(warning)}})],resolve:{alias:{'@':path.join(root,'frontend/src')}},server:{host:'127.0.0.1',port:1437,strictPort:true,fs:{allow:[root]}}});
await server.listen();
const browser=await chromium.launch({headless:true,executablePath:process.env.JARVIS_TEST_CHROMIUM});
const page=await browser.newPage({viewport:{width:1280,height:960}});
page.setDefaultTimeout(20000);
const errors=[];page.on('pageerror',error=>errors.push(error.message));
try{
    await page.goto('http://127.0.0.1:1437/tests/settings/index.html');
    const nav=page.getByRole('navigation',{name:'Разделы настроек'});
    const save=page.getByRole('button',{name:'Сохранить изменения',exact:true});
    await page.getByText('Все изменения сохранены',{exact:true}).waitFor();
    assert.equal(await nav.getByRole('button').count(),8);
    assert.equal(await save.isDisabled(),true);
    await page.screenshot({path:path.join(root,'target/settings-general-dark.png'),fullPage:true});
    await nav.getByRole('button',{name:'Голос и звук',exact:true}).click();
    await page.getByRole('button',{name:/Обученный голос XTTS/}).click();
    await page.getByText('Есть несохранённые изменения',{exact:true}).waitFor();
    await nav.getByRole('button',{name:'Основные',exact:true}).click();
    await nav.getByRole('button',{name:'Голос и звук',exact:true}).click();
    assert.equal(await page.getByRole('button',{name:/Обученный голос XTTS/}).getAttribute('aria-pressed'),'true');
    await page.screenshot({path:path.join(root,'target/settings-voice-dark.png'),fullPage:true});
    await save.click();
    await page.getByText('✓ Изменения сохранены',{exact:true}).waitFor();
    const write=await page.evaluate(()=>window.fixture.writes.at(-1));
    assert.equal(write.find(entry=>entry.key==='tts_mode').val,'xtts');
    assert.equal(write.length,15);
    await page.getByRole('button',{name:/Silero/}).click();
    await page.getByRole('button',{name:'Отменить',exact:true}).click();
    assert.equal(await page.getByRole('button',{name:/Обученный голос XTTS/}).getAttribute('aria-pressed'),'true');
    await page.getByRole('button',{name:/Silero/}).click();
    await page.evaluate(()=>window.fixture.failWrite=true);
    await save.click();await page.getByRole('alert').filter({hasText:'Fictional save failure'}).waitFor();
    assert.equal(await save.isEnabled(),true);
    await page.getByRole('button',{name:'Отменить',exact:true}).click();
    for(const title of ['Нейросеть','Устройства','Данные и копии','Сайты и команды','Дополнительно','О приложении']){
        await nav.getByRole('button',{name:title,exact:true}).click();
        assert.equal(await page.getByRole('heading',{name:title,exact:true,level:2}).isVisible(),true);
        if(['Нейросеть','Устройства','Дополнительно'].includes(title))await page.screenshot({path:path.join(root,'target/settings-'+({'Нейросеть':'models','Устройства':'devices','Дополнительно':'advanced'}[title])+'.png'),fullPage:true});
    }
    await nav.getByRole('button',{name:'Нейросеть',exact:true}).click();
    await page.getByLabel('Модель DeepSeek',{exact:true}).fill('fictional-edited-model');
    await nav.getByRole('button',{name:'Устройства',exact:true}).click();
    await nav.getByRole('button',{name:'Нейросеть',exact:true}).click();
    assert.equal(await page.getByLabel('Модель DeepSeek',{exact:true}).inputValue(),'fictional-edited-model');
    await nav.getByRole('button',{name:'Основные',exact:true}).click();
    await page.getByLabel('Тема приложения',{exact:true}).selectOption('light');
    assert.equal(await page.locator('html').getAttribute('data-theme'),'light');
    await page.screenshot({path:path.join(root,'target/settings-general-light.png'),fullPage:true});
    await page.setViewportSize({width:680,height:900});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await page.screenshot({path:path.join(root,'target/settings-narrow.png'),fullPage:true});
    await page.goto('http://127.0.0.1:1437/tests/settings/index.html?loadError');
    await page.getByRole('alert').filter({hasText:'Не удалось загрузить настройки'}).waitFor();
    assert.equal(await page.getByRole('button',{name:'Сохранить изменения',exact:true}).isDisabled(),true);
    assert.deepEqual(errors,[]);
    fs.writeFileSync(path.join(root,'target/settings-ui-tests.log'),'PASS: navigation, drafts across sections, save/cancel/failure, isolated settings, light theme, narrow layout, load-failure guard.\n');
    console.log('PASS: settings UI with fictional preferences; no real profile writes.');
}catch(error){await page.screenshot({path:path.join(root,'target/settings-test-failure.png'),fullPage:true});console.error('Browser errors:',errors);throw error}finally{await browser.close();await server.close()}
